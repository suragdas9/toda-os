/**
 * fb_init — Initialize the Framebuffer and activate QEMU display
 */
result_t fb_init(void) {
    uart_print("[DISPLAY]  Initializing 480x800 ARGB32 Mobile Framebuffer...\n");

    /* Clear framebuffer to background color */
    fb_clear(COLOR_BG_TOP);

    /* Perform QEMU hardware handshake to turn on screen */
    qemu_ramfb_init();

    fb_ready = true;
    return TODA_OK;
}

uint32_t* fb_get_buffer(void) {
    return fb_buffer;
}

void fb_clear(uint32_t color) {
    for (int i = 0; i < FB_WIDTH * FB_HEIGHT; i++) {
        fb_buffer[i] = color;
    }
}

void fb_draw_pixel(int x, int y, uint32_t color) {
    if (x < 0 || x >= FB_WIDTH || y < 0 || y >= FB_HEIGHT) return;
    
    uint32_t a = (color >> 24) & 0xFF;
    if (a == 255) {
        fb_buffer[y * FB_WIDTH + x] = color;
    } else if (a > 0) {
        uint32_t bg = fb_buffer[y * FB_WIDTH + x];
        uint32_t rb = ((color & 0x00FF00FF) * a + (bg & 0x00FF00FF) * (255 - a)) >> 8;
        uint32_t g  = ((color & 0x0000FF00) * a + (bg & 0x0000FF00) * (255 - a)) >> 8;
        fb_buffer[y * FB_WIDTH + x] = 0xFF000000 | (rb & 0x00FF00FF) | (g & 0x0000FF00);
    }
}

void fb_draw_rect(int x, int y, int w, int h, uint32_t color) {
    for (int j = y; j < y + h; j++) {
        for (int i = x; i < x + w; i++) {
            fb_draw_pixel(i, j, color);
        }
    }
}

void fb_draw_gradient_v(int x, int y, int w, int h, uint32_t top_col, uint32_t bot_col) {
    int r1 = (top_col >> 16) & 0xFF, g1 = (top_col >> 8) & 0xFF, b1 = top_col & 0xFF;
    int r2 = (bot_col >> 16) & 0xFF, g2 = (bot_col >> 8) & 0xFF, b2 = bot_col & 0xFF;

    for (int j = 0; j < h; j++) {
        int r = r1 + ((r2 - r1) * j) / h;
        int g = g1 + ((g2 - g1) * j) / h;
        int b = b1 + ((b2 - b1) * j) / h;
        uint32_t col = 0xFF000000 | (r << 16) | (g << 8) | b;
        for (int i = x; i < x + w; i++) {
            fb_draw_pixel(i, y + j, col);
        }
    }
}

void fb_draw_rounded_rect(int x, int y, int w, int h, int radius, uint32_t color) {
    int r2 = radius * radius;
    for (int j = 0; j < h; j++) {
        for (int i = x; i < x + w; i++) {
            int local_x = i - x;
            int local_y = j - y;
            bool in_corner = false;

            if (local_x < radius && local_y < radius) {
                int dx = radius - local_x, dy = radius - local_y;
                if (dx * dx + dy * dy > r2) in_corner = true;
            } else if (local_x >= w - radius && local_y < radius) {
                int dx = local_x - (w - radius - 1), dy = radius - local_y;
                if (dx * dx + dy * dy > r2) in_corner = true;
            } else if (local_x < radius && local_y >= h - radius) {
                int dx = radius - local_x, dy = local_y - (h - radius - 1);
                if (dx * dx + dy * dy > r2) in_corner = true;
            } else if (local_x >= w - radius && local_y >= h - radius) {
                int dx = local_x - (w - radius - 1), dy = local_y - (h - radius - 1);
                if (dx * dx + dy * dy > r2) in_corner = true;
            }

            if (!in_corner) {
                fb_draw_pixel(i, j, color);
            }
        }
    }
}

void fb_draw_circle(int cx, int cy, int radius, uint32_t color) {
    int r2 = radius * radius;
    for (int y = -radius; y <= radius; y++) {
        for (int x = -radius; x <= radius; x++) {
            if (x * x + y * y <= r2) {
                fb_draw_pixel(cx + x, cy + y, color);
            }
        }
    }
}

void fb_draw_circle_outline(int cx, int cy, int radius, int thickness, uint32_t color) {
    int r_out = radius * radius;
    int r_in = (radius - thickness) * (radius - thickness);
    for (int y = -radius; y <= radius; y++) {
        for (int x = -radius; x <= radius; x++) {
            int d = x * x + y * y;
            if (d <= r_out && d >= r_in) {
                fb_draw_pixel(cx + x, cy + y, color);
            }
        }
    }
}

void fb_draw_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    if (c < 32 || c > 122) c = '?';
    const uint8_t* glyph = font_8x16[(int)(c - 32)];

    for (int row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                fb_draw_pixel(x + col, y + row, fg);
            } else if (bg != COLOR_TRANSPARENT) {
                fb_draw_pixel(x + col, y + row, bg);
            }
        }
    }
}

void fb_draw_string(int x, int y, const char* str, uint32_t fg, uint32_t bg) {
    int cur_x = x;
    while (*str) {
        fb_draw_char(cur_x, y, *str, fg, bg);
        cur_x += 8;
        str++;
    }
}

void fb_draw_string_large(int x, int y, const char* str, uint32_t fg) {
    int cur_x = x;
    while (*str) {
        char c = *str;
        if (c < 32 || c > 122) c = '?';
        const uint8_t* glyph = font_8x16[(int)(c - 32)];

        for (int row = 0; row < 16; row++) {
            uint8_t bits = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    fb_draw_pixel(cur_x + col * 2,     y + row * 2,     fg);
                    fb_draw_pixel(cur_x + col * 2 + 1, y + row * 2,     fg);
                    fb_draw_pixel(cur_x + col * 2,     y + row * 2 + 1, fg);
                    fb_draw_pixel(cur_x + col * 2 + 1, y + row * 2 + 1, fg);
                }
            }
        }
        cur_x += 16;
        str++;
    }
}

void fb_draw_string_huge(int x, int y, const char* str, uint32_t fg) {
    int cur_x = x;
    while (*str) {
        char c = *str;
        if (c < 32 || c > 122) c = '?';
        const uint8_t* glyph = font_8x16[(int)(c - 32)];

        for (int row = 0; row < 16; row++) {
            uint8_t bits = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    fb_draw_rect(cur_x + col * 4, y + row * 4, 4, 4, fg);
                }
            }
        }
        cur_x += 32;
        str++;
    }
}
